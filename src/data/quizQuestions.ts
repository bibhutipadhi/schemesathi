export function getLocalizedQuizQuestion(
  q: CivicQuizQuestion,
  language: LanguageCode
): {
  question: string;
  options: string[];
  explanation: string;
  schemeRelated?: string;
  category: string;
} {
  const trans = q.translations?.[language];
  if (trans) {
    return {
      question: trans.question || q.question,
      options: trans.options && trans.options.length === q.options.length ? trans.options : q.options,
      explanation: trans.explanation || q.explanation,
      schemeRelated: trans.schemeRelated || q.schemeRelated,
      category: trans.category || q.category,
    };
  }
  return {
    question: q.question,
    options: q.options,
    explanation: q.explanation,
    schemeRelated: q.schemeRelated,
    category: q.category,
  };
}

